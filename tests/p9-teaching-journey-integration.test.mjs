import test from 'node:test';
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { classroom, openClassroom, planPdf, upload } from './p6-integration-helpers.mjs';
import { digest } from './p4-integration-helpers.mjs';
import { withJourney, ok, request, rootOf, detail, inviteExplicitly, rejectUnchanged, academicHash } from './p9-journey-helpers.mjs';

test('P9 joined teaching: verified accounts, scanned private classroom, explicit enrollments, Plan/Library/Muro and scoped news', { timeout: 330000 }, async () => {
  await withJourney('teaching', async world => {
    const { runtime, T, S, P, room, scratch } = world, root = rootOf(room);
    await inviteExplicitly(world, P);
    assert.equal((await detail(T.page, room)).role, 'teacher');
    assert.equal((await ok(S.page, 'GET', root)).role, 'student');
    const foreign = await classroom(P.page, T.page, 'P9 opposite classroom');
    assert.equal((await ok(T.page, 'GET', rootOf(foreign))).role, 'student');
    const mine = await ok(T.page, 'GET', '/classrooms');
    assert.ok(mine.teach.some(row => row.id === room.id)); assert.ok(mine.study.some(row => row.id === foreign.id));
    await rejectUnchanged(runtime.db, () => request(T.page, 'POST', `${rootOf(foreign)}/plan`, {
      revision: '1', operation: { action: 'addUnit', name: 'Forbidden global teacher' } }), 403);
    // A real private draft and scan must not enroll or publish through mere saving.
    const draft = await ok(T.page, 'POST', '/classrooms/drafts', {}), membersBefore = await academicHash(runtime.db);
    await rejectUnchanged(runtime.db, () => request(S.page, 'GET', `/classrooms/drafts/${draft.id}`), 403);
    assert.equal(await academicHash(runtime.db), membersBefore);
    const original = await detail(T.page, room), unit = original.units[0], topic = unit.topics[0];
    assert.equal((await ok(S.page, 'GET', `/files/${room.fileId}/content`)).digest, digest(room.bytes));
    const planBytes = await planPdf('P9 genuine second plan'), version = await upload(T.page, { kind: 'classroom', id: room.id }, planBytes);
    await ok(T.page, 'POST', `${root}/plan`, { revision: (await detail(T.page, room)).revision,
      operation: { action: 'appendVersion', fileId: version.id } });
    const plans = (await detail(T.page, room)).plans;
    assert.deepEqual(plans.map(row => row.version), [2, 1]); assert.equal(plans[1].fileId, room.fileId);
    await openClassroom(T.page, runtime.origin, 'P9 teaching classroom');
    await T.page.getByRole('button', { name: 'Plan', exact: true }).click();
    await T.page.getByRole('region', { name: 'Plan de estudio', exact: true }).locator('summary').filter({ hasText: /^Administrar plan/ }).click();
    const topicState = T.page.getByRole('region', { name: 'Plan de estudio', exact: true }).getByLabel('Estado de First topic');
    assert.equal(await topicState.count(), 1, 'One scoped First-topic state control is required');
    let response = T.page.waitForResponse(r => r.url().endsWith(`${room.id}/plan`) && r.request().method() === 'POST');
    await topicState.selectOption('NEXT');
    assert.equal((await response).status(), 200); await (await response).json();
    assert.equal(await topicState.count(), 1, 'One scoped First-topic state control is required');
    response = T.page.waitForResponse(r => r.url().endsWith(`${room.id}/plan`) && r.request().method() === 'POST');
    await topicState.selectOption('TAUGHT');
    assert.equal((await response).status(), 200); await (await response).json();
    assert.equal((await detail(T.page, room)).units[0].topics[0].status, 'TAUGHT');
    await rejectUnchanged(runtime.db, () => request(S.page, 'POST', `${root}/plan`, {
      revision: (original.revision), operation: { action: 'setTopicState', id: topic.id, status: 'PENDING' } }), 403);
    await T.page.getByRole('button', { name: 'Biblioteca', exact: true }).click();
    const materialBytes = await planPdf('P9 real teaching material');
    await T.page.getByLabel('Archivo del material', { exact: true }).setInputFiles({ name: 'p9-material.pdf', mimeType: 'application/pdf', buffer: materialBytes });
    await T.page.getByText('Archivo aprobado: p9-material.pdf. Completa los datos para publicarlo.', { exact: true }).waitFor();
    assert.deepEqual(await ok(S.page, 'GET', `${root}/library`), []);
    await T.page.getByLabel('Nombre del material', { exact: true }).fill('Joined published material');
    await T.page.getByLabel('Unidad del material', { exact: true }).selectOption(unit.id);
    await T.page.getByLabel('Tema del material', { exact: true }).selectOption(topic.id);
    response = T.page.waitForResponse(r => r.url().endsWith(`${room.id}/library`) && r.request().method() === 'POST');
    await T.page.getByRole('button', { name: 'Publicar material', exact: true }).click();
    assert.equal((await response).status(), 200); await (await response).json();
    const [material] = await ok(S.page, 'GET', `${root}/library`);
    assert.equal(material.unitId, unit.id); assert.equal(material.topicId, topic.id); assert.equal(material.ready, true);
    await openClassroom(S.page, runtime.origin, 'P9 teaching classroom');
    await S.page.getByRole('button', { name: 'Plan', exact: true }).click();
    await S.page.getByRole('link', { name: 'Descargar plan · Versión 2', exact: true }).waitFor();
    const studentPlan = S.page.getByRole('region', { name: 'Plan de estudio', exact: true });
    assert.equal(await studentPlan.getByLabel('Tema del plan', { exact: true }).count(), 1);
    assert.equal(await studentPlan.getByLabel('Estado de First topic', { exact: true }).count(), 0);
    assert.equal(await studentPlan.getByLabel('Avance de First topic', { exact: true }).count(), 0);
    assert.equal(await studentPlan.getByText('Administrar plan', { exact: false }).count(), 0);
    assert.equal(await studentPlan.getByLabel('Archivo del plan (PDF o DOCX)', { exact: true }).count(), 0);
    await S.page.getByRole('button', { name: 'Biblioteca', exact: true }).click();
    await S.page.getByRole('article', { name: 'Joined published material', exact: true }).waitFor();
    assert.equal(await S.page.getByLabel('Archivo del material', { exact: true }).count(), 0);
    assert.equal((await ok(S.page, 'GET', `/files/${material.fileId}/content`)).digest, digest(materialBytes));
    await T.page.getByRole('button', { name: 'Muro', exact: true }).click();
    await T.page.getByLabel('Publicar aviso', { exact: true }).fill('Joined teacher notice');
    response = T.page.waitForResponse(r => r.url().endsWith(`${room.id}/wall`) && r.request().method() === 'POST');
    await T.page.getByRole('button', { name: 'Publicar aviso', exact: true }).click();
    assert.equal((await response).status(), 200); await (await response).json();
    await T.page.getByText('Publicación guardada.', { exact: true }).waitFor();
    const wall = await ok(S.page, 'GET', `${root}/wall`), post = wall.posts.find(row => row.body === 'Joined teacher notice');
    assert.equal(post.type, 'NOTICE'); assert.ok(post.authorName && post.initials); assert.equal(Object.hasOwn(post, 'email'), false);
    const events = await ok(S.page, 'GET', '/classrooms/notifications'), event = events.find(row => row.eventType === 'WALL_NOTICE' && row.classroomId === room.id);
    assert.ok(event); assert.equal(events.some(row => row.classroomId === foreign.id), false);
    await rejectUnchanged(runtime.db, () => request(T.page, 'POST', `/classrooms/notifications/${event.id}/open`, {}), 403);
    await ok(S.page, 'POST', `/classrooms/notifications/${event.id}/open`, {});
    await S.page.getByRole('button', { name: 'Muro', exact: true }).click();
    await S.page.getByText('Joined teacher notice', { exact: true }).waitFor();
    await S.page.getByLabel('Publicar consulta', { exact: true }).fill('Joined student query');
    response = S.page.waitForResponse(r => r.url().endsWith(`${room.id}/wall`) && r.request().method() === 'POST');
    await S.page.getByRole('button', { name: 'Publicar consulta', exact: true }).click();
    assert.equal((await response).status(), 200); await (await response).json();
    assert.equal((await ok(T.page, 'GET', `${root}/wall`)).posts[0].type, 'QUERY');
    await S.page.screenshot({ path: join(scratch, 'joined-student-wall.png'), fullPage: true });
    const before = await academicHash(runtime.db); await runtime.restartData(); assert.equal(await academicHash(runtime.db), before);
    assert.equal((await ok(S.page, 'GET', `/files/${version.id}/content`)).digest, digest(planBytes));
    assert.equal((await ok(S.page, 'GET', `/files/${material.fileId}/content`)).digest, digest(materialBytes));
    console.log('P9 teaching: real3accounts/capturedinvitation/private-draft/plan2/material/Muro/currentroles/restart PASS');
  }, { peer: true });
});
