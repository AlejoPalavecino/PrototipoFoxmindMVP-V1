import test from 'node:test';
import assert from 'node:assert/strict';
import { PDFDocument } from 'pdf-lib';
import { createHash } from 'node:crypto';
import { openClassroom } from './p6-integration-helpers.mjs';
import { withJourney, ok, request, rootOf, openActivity, selectClassroomSection, openOwnResult } from './p9-journey-helpers-current.mjs';

const operationResponse = (page, roomId, action) => page.waitForResponse(response =>
  new URL(response.url()).pathname === `/api/v1/classrooms/${roomId}/activities`
  && response.request().method() === 'POST' && response.request().postDataJSON()?.operation?.action === action);

test('Brújula completa real: aula manual obligatoria, autoría privada, criterios con override y centro de notificaciones', { timeout: 330000 }, async () => {
  await withJourney('brujula-complete', async original => {
    const { T, S, runtime } = original;
    const classroomName = 'P9 brujula-complete manual classroom';
    const uploads = [], activityWrites = [];
    T.page.on('request', value => {
      if (value.method() === 'POST' && new URL(value.url()).pathname === '/api/v1/files') uploads.push(true);
      if (value.method() === 'POST' && /\/classrooms\/[^/]+\/activities$/.test(new URL(value.url()).pathname)) activityWrites.push(value.postDataJSON()?.operation?.action);
    });
    await T.page.goto(`${runtime.origin}/mis-aulas`);
    const draftResponse = T.page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/classrooms/drafts' && response.request().method() === 'POST');
    await T.page.getByRole('button', { name: 'Crear aula', exact: true }).click();
    const draftCreated = await draftResponse; assert.equal(draftCreated.status(), 200);
    const draft = await draftCreated.json();
    let wizard = T.page.getByRole('dialog', { name: 'Crear aula', exact: true });
    await wizard.getByLabel('Nombre del aula', { exact: true }).fill(classroomName);
    await wizard.getByLabel('Materia', { exact: true }).fill('Ciencias');
    await wizard.getByLabel('División', { exact: true }).fill('A');
    await wizard.getByLabel('Ciclo lectivo', { exact: true }).fill('2026');
    const pdf = await PDFDocument.create(); pdf.addPage();
    const planBytes = Buffer.from(await pdf.save());
    await wizard.getByRole('button', { name: 'Continuar al plan', exact: true }).click();
    const reserved = T.page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/files' && response.request().method() === 'POST');
    await wizard.locator('input[type=file]').setInputFiles({ name: 'manual-plan.pdf', mimeType: 'application/pdf', buffer: planBytes });
    const uploaded = await reserved; assert.equal(uploaded.status(), 201);
    const planFileId = (await uploaded.json()).id;
    await wizard.getByText('Aprobado para usar', { exact: true }).waitFor({ timeout: 30000 });
    await wizard.getByRole('radio', { name: /Cargar manualmente/ }).check();
    await wizard.getByRole('button', { name: 'Continuar a unidades', exact: true }).click();
    let publishAttempts = 0;
    const observePublish = value => { if (value.method() === 'POST' && new URL(value.url()).pathname === `/api/v1/classrooms/drafts/${draft.id}/publish`) publishAttempts++; };
    T.page.on('request', observePublish);
    try {
      await wizard.getByRole('button', { name: 'Guardar plan y continuar', exact: true }).click();
      await wizard.getByText(/Agregá al menos una unidad con un tema/).waitFor();
      assert.equal(publishAttempts, 0, 'Empty plan cannot reach publication');
      await wizard.getByRole('button', { name: 'Editar el plan como texto', exact: true }).click();
      const planEditor = T.page.getByRole('dialog', { name: 'Editar el plan como texto', exact: true });
      await planEditor.getByRole('textbox', { name: 'Texto del plan', exact: true }).fill('Unidad 1 · Inicio\nTema inicial\nTema siguiente');
      await planEditor.getByRole('button', { name: 'Preparar esquema', exact: true }).click();
      await planEditor.waitFor({ state: 'hidden' });
      await wizard.getByRole('button', { name: 'Guardar plan y continuar', exact: true }).click();
      const publishing = T.page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1/classrooms/drafts/${draft.id}/publish` && response.request().method() === 'POST');
      await wizard.getByRole('button', { name: 'Confirmar y crear aula', exact: true }).click();
      const published = await publishing; assert.equal(published.status(), 200);
      const room = { ...(await published.json()), name: classroomName };
      await T.page.getByRole('heading', { name: classroomName, exact: true }).waitFor();
      assert.equal(publishAttempts, 1);
      assert.deepEqual(uploads, [true], 'Manual creation uploads exactly the provided plan');
      const downloadedPlan = await T.page.request.get(`${runtime.origin}/api/v1/files/${planFileId}/content`);
      assert.equal(downloadedPlan.status(), 200);
      assert.equal(createHash('sha256').update(await downloadedPlan.body()).digest('hex'), createHash('sha256').update(planBytes).digest('hex'));
      const state = await ok(T.page, 'GET', rootOf(room));
      assert.equal(state.accessCode,room.code,'teacher can recover the current code after reload');
      assert.equal(state.units.length, 1); assert.equal(state.units[0].topics.length, 2);
      assert.equal((await runtime.db.query('SELECT count(*)::int n FROM study_plan_versions WHERE classroom_id=$1', [room.id])).rows[0].n, 1);
      const preview = await ok(S.page, 'POST', '/classrooms/codes/preview', { code: room.code });
      await ok(S.page, 'POST', '/classrooms/codes/confirm', { confirmation: preview.confirmation });
      assert.equal(Object.hasOwn(await ok(S.page,'GET',rootOf(room)),'accessCode'),false,'code recovery stays teacher-only');
      const world = { ...original, label: 'brujula-complete manual', room }, root = rootOf(room);

      await openClassroom(T.page, runtime.origin, classroomName);
      await selectClassroomSection(T.page, 'activities', 'Actividades');
      await T.page.getByRole('button', { name: 'Crear actividad', exact: true }).click();
      await T.page.getByRole('dialog', { name: 'Crear actividad', exact: true }).getByRole('button', { name: 'Crear manualmente', exact: true }).click();
      const editor = T.page.getByRole('region', { name: 'Editar actividad', exact: true });
      await editor.getByRole('heading', { name: 'Paso 1 de 3 · Alcance', exact: true }).waitFor();
      await editor.getByRole('radio', { name: /^Trabajo práctico/ }).check();
      await editor.getByRole('checkbox', { name: 'Tema inicial', exact: true }).check();
      await editor.getByRole('button', { name: 'Continuar', exact: true }).click();
      await editor.getByRole('heading', { name: 'Paso 2 de 3 · Contenido', exact: true }).waitFor();
      await editor.getByRole('checkbox', { name: 'Archivos de entrega obligatorios', exact: true }).uncheck();
      const title = 'Actividad manual con campos y criterios';
      const objective = 'Relacionar dos conceptos con evidencia propia.';
      const comment = 'Usá ejemplos de la clase para justificar la respuesta.';
      await editor.getByLabel('Título de la actividad', { exact: true }).fill(title);
      await editor.getByLabel('Objetivo de aprendizaje', { exact: true }).fill(objective);
      await editor.getByLabel('Consignas', { exact: true }).fill('Explicá una relación entre los temas trabajados.');
      const materials = editor.getByRole('region', { name: 'Materiales y comentario docente', exact: true });
      await materials.getByLabel(/Comentario para el aula/).fill(comment);
      assert.equal(await editor.getByText('Corrección asistida por IA',{exact:true}).count(),0);
      await editor.getByRole('button', { name: /^Rúbrica/ }).click();
      await editor.getByLabel('Criterio 1', { exact: true }).fill('Evidencia');
      await editor.getByLabel('Descripción del criterio 1', { exact: true }).fill('Fundamenta la relación con ejemplos.');
      await editor.getByLabel('Ponderación del criterio 1 (%)', { exact: true }).fill('60');
      await editor.getByRole('button', { name: 'Agregar criterio', exact: true }).click();
      await editor.getByLabel('Criterio 2', { exact: true }).fill('Claridad');
      await editor.getByLabel('Descripción del criterio 2', { exact: true }).fill('Presenta una explicación comprensible.');
      await editor.getByLabel('Ponderación del criterio 2 (%)', { exact: true }).fill('40');
      await editor.getByRole('button', { name: 'Continuar a revisión', exact: true }).click();
      await editor.getByRole('region', { name: 'Revisión del borrador', exact: true }).getByText(objective, { exact: true }).waitFor();
      assert.deepEqual(activityWrites, [], 'Method selection, editing and review never create or publish');
      const creating = operationResponse(T.page, room.id, 'create'), saving = operationResponse(T.page, room.id, 'save');
      await editor.getByRole('button', { name: 'Guardar borrador', exact: true }).click();
      const created = await creating, saved = await saving;
      assert.equal(created.status(), 200); assert.equal(saved.status(), 200);
      const activity = { id: (await created.json()).id, title, type: 'ASSIGNMENT' };
      assert.deepEqual(activityWrites, ['create', 'save']);
      const persisted = (await ok(T.page, 'GET', `${root}/activities/${activity.id}/preview`)).activity;
      assert.equal(persisted.objective, objective); assert.equal(persisted.teacherComment, comment);
      assert.equal(persisted.status, 'DRAFT');
      assert.deepEqual(persisted.evaluationRubric.map(row => row.weight), [60, 40]);
      assert.equal((await request(S.page, 'GET', `${root}/activities/${activity.id}/session`)).status, 403);
      assert.ok(!(await ok(S.page, 'GET', '/classrooms/notifications')).some(item => item.activityId === activity.id));
      await editor.waitFor({state:'hidden'});
      await T.page.getByText('Solo vos podés ver este borrador.',{exact:true}).waitFor();
      await T.page.getByRole('button',{name:'Revisar para asignar',exact:true}).click();
      await editor.getByRole('button', { name: 'Publicar actividad', exact: true }).click();
      assert.deepEqual(activityWrites, ['create', 'save'], 'Opening the confirmation does not assign');
      const assigned = operationResponse(T.page, room.id, 'publish');
      await editor.getByRole('dialog', { name: 'Confirmá la publicación', exact: true }).getByRole('button', { name: 'Asignar al aula', exact: true }).click();
      assert.equal((await assigned).status(), 200); await editor.waitFor({ state: 'hidden' });
      const publicActivity = (await ok(S.page, 'GET', `${root}/activities/${activity.id}/session`)).activity;
      assert.equal(publicActivity.objective, objective); assert.equal(publicActivity.teacherComment, comment);
      assert.equal('aiGradingRubric' in publicActivity, false);
      assert.equal((await ok(S.page,'GET',`${root}/activities`)).activities.find(item=>item.id===activity.id).studentState,'PENDING');
      await S.page.goto(`${runtime.origin}/mis-aulas?aula=${room.id}&destino=activity&activityId=${activity.id}&mode=respond`);
      await S.page.getByRole('region',{name:'Consulta de actividad',exact:true}).waitFor();
      const activityPreview=S.page.getByRole('region',{name:'Consulta de actividad',exact:true});
      await activityPreview.getByText(objective,{exact:true}).waitFor();await activityPreview.getByText(comment,{exact:true}).waitFor();
      assert.equal((await ok(S.page,'GET',`${root}/activities/${activity.id}/session`)).attempt,null,'Loading a response URL cannot start an attempt');
      await S.page.goto(`${runtime.origin}/inicio`);
      const homeStart=S.page.waitForResponse(response=>response.url().endsWith(`/${activity.id}/start`)&&response.request().method()==='POST');
      const pendingCard = S.page.locator('article.learning-tile').filter({ has: S.page.getByRole('heading', { name: title, exact: true }) });
      await pendingCard.getByRole('button', { name: 'Empezar', exact: true }).click();
      assert.equal((await homeStart).status(),200);
      await S.page.getByLabel('Tu respuesta',{exact:true}).waitFor();
      const attemptId = (await ok(S.page, 'GET', `${root}/activities/${activity.id}/session`)).attempt.id;
      const practicalText='Observé especies y sus relaciones.\nRespuesta escrita sintética 😀';
      await S.page.getByRole('textbox',{name:'Tu respuesta',exact:true}).fill(practicalText);
      const written=S.page.waitForResponse(response=>new URL(response.url()).pathname===`/api/v1${root}/attempts/${attemptId}/practical-response`&&response.request().method()==='POST');
      await S.page.getByRole('button',{name:'Guardar borrador',exact:true}).click();assert.equal((await written).status(),200);
      assert.equal((await ok(S.page,'GET',`${root}/activities/${activity.id}/session`)).attempt.practicalResponse,practicalText);
      await S.page.getByRole('button', { name: 'Revisar entrega', exact: true }).click();
      const submission = S.page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1${root}/attempts/${attemptId}/submit-practical` && response.request().method() === 'POST');
      await S.page.getByRole('button', { name: 'Confirmar envío del trabajo', exact: true }).click();
      assert.equal((await submission).status(), 200);
      assert.equal((await ok(T.page,'GET',`${root}/activities`)).activities.find(item=>item.id===activity.id).pendingReviewCount,1);
      assert.equal('pendingReviewCount' in (await ok(S.page,'GET',`${root}/activities`)).activities.find(item=>item.id===activity.id),false);
      assert.equal((await ok(S.page,'GET',`${root}/activities`)).activities.find(item=>item.id===activity.id).studentState,'SUBMITTED');

      await T.page.goto(`${runtime.origin}/inicio`);
      const reviewGroup = T.page.locator('section.review-group').filter({ has: T.page.getByRole('heading', { name: title, exact: true }) });
      await reviewGroup.getByRole('button', { name: /^Revisar / }).click();
      const grading = T.page.getByRole('region', { name: 'Corrección privada del intento', exact: true });
      await grading.getByText(practicalText,{exact:true}).waitFor();
      await grading.getByRole('textbox', { name: 'Puntaje de Evidencia', exact: true }).fill('8');
      await grading.getByRole('textbox', { name: 'Puntaje de Claridad', exact: true }).fill('5');
      assert.equal(await grading.locator('output').innerText(), '6,80');
      assert.equal(await grading.getByRole('textbox', { name: 'Nota final', exact: true }).inputValue(), '', 'A suggestion must never silently become the final grade');
      await grading.getByRole('button', { name: 'Usar nota sugerida', exact: true }).click();
      assert.equal(await grading.getByRole('textbox', { name: 'Nota final', exact: true }).inputValue(), '6,80');
      await grading.getByRole('textbox', { name: 'Nota final', exact: true }).fill('9,25');
      await grading.getByRole('button', { name: 'Devolución', exact: true }).click();
      await grading.getByRole('textbox', { name: 'Devolución general opcional', exact: true }).fill('Devolución publicada explícitamente.');
      const privateSave = T.page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1${root}/attempts/${attemptId}/grading` && response.request().method() === 'POST');
      await grading.getByRole('button', { name: 'Guardar corrección privada', exact: true }).click();
      const privateResponse = await privateSave; assert.equal(privateResponse.status(), 200);
      const privateData = await privateResponse.json();
      assert.equal(privateData.grade.suggestedGrade, '6.80'); assert.equal(privateData.grade.finalGradeOverride, '9.25');
      assert.equal(privateData.grade.isPublished, false);
      assert.deepEqual(await ok(S.page, 'GET', `${root}/attempts/${attemptId}/result`), { status: 'pending', attemptId });
      assert.ok(!(await ok(S.page, 'GET', '/classrooms/notifications')).some(item => item.activityId === activity.id && item.eventType === 'GRADE_PUBLISHED'));
      await grading.getByRole('button', { name: 'Publicar calificación', exact: true }).click();
      const gradePublication = T.page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1${root}/attempts/${attemptId}/publish-grade` && response.request().method() === 'POST');
      await grading.getByRole('region', { name: 'Confirmar publicación de calificación', exact: true }).getByRole('button', { name: 'Confirmar publicación', exact: true }).click();
      assert.equal((await gradePublication).status(), 200);
      assert.equal((await ok(T.page,'GET',`${root}/activities`)).activities.find(item=>item.id===activity.id).pendingReviewCount,0);
      assert.equal((await ok(S.page,'GET',`${root}/activities`)).activities.find(item=>item.id===activity.id).studentState,'REVIEWED');
      const { data: result, region } = await openOwnResult(world, activity, attemptId);
      assert.equal(result.grade.finalGrade, '9.25'); assert.equal(result.grade.suggestedGrade, '6.80');
      assert.deepEqual(result.grade.rubricSnapshot, persisted.evaluationRubric);
      assert.deepEqual(result.grade.rubricMarks.map(mark => Number(mark.score)), [8, 5]);
      await region.getByRole('region', { name: 'Evaluación por criterios publicada', exact: true }).getByText('Evidencia', { exact: true }).waitFor();
      assert.doesNotMatch(await region.innerText(), /Instrucción exclusivamente docente/);

      await grading.getByRole('button', { name: 'Volver al historial', exact: true }).click();
      const teacherHistory = T.page.getByRole('region', { name: 'Entregas e historial de intentos', exact: true });
      await teacherHistory.getByRole('button', { name: 'Volver a actividades', exact: true }).click();
      await teacherHistory.waitFor({ state: 'hidden' });
      await selectClassroomSection(T.page, 'wall', 'Muro');
      await T.page.getByRole('button', { name: 'Publicar aviso', exact: true }).click();
      const wall = T.page.getByRole('dialog', { name: 'Publicar aviso', exact: true });
      await wall.getByRole('textbox', { name: 'Título', exact: true }).fill('Título real del aviso');
      await wall.getByRole('textbox', { name: 'Mensaje', exact: true }).fill('Contenido del aviso para el grupo.');
      const wallPublication = T.page.waitForResponse(response => new URL(response.url()).pathname === `/api/v1${root}/wall` && response.request().method() === 'POST');
      await wall.getByRole('button', { name: 'Publicar aviso', exact: true }).click();
      assert.equal((await wallPublication).status(), 200);
      assert.ok((await ok(S.page, 'GET', `${root}/wall`)).posts.some(post => post.title === 'Título real del aviso' && post.body === 'Contenido del aviso para el grupo.'));
      const teacherReads = (await ok(T.page, 'GET', '/classrooms/notifications')).map(item => [item.id, item.readAt]);
      await S.page.goto(`${runtime.origin}/notificaciones`);
      const center = S.page.getByRole('region', { name: 'Tu bandeja de notificaciones', exact: true });
      await center.getByRole('button', { name: 'Actividades', exact: true }).click();
      await center.getByRole('heading', { name: 'Calificación publicada', exact: true }).waitFor();
      assert.equal(await center.getByRole('heading', { name: 'Nuevo aviso del docente', exact: true }).count(), 0);
      await center.getByRole('button', { name: 'Todos los tipos', exact: true }).click();
      await center.getByRole('heading', { name: 'Nuevo aviso del docente', exact: true }).waitFor();
      await center.getByRole('button', { name: 'Marcar todas como leídas', exact: true }).click();
      await S.page.getByText('Estás al día', { exact: true }).waitFor();
      assert.equal(await center.getByRole('button', { name: 'Marcar todas como leídas', exact: true }).isDisabled(), true);
      assert.ok((await ok(S.page, 'GET', '/classrooms/notifications')).every(item => item.readAt));
      assert.deepEqual((await ok(T.page, 'GET', '/classrooms/notifications')).map(item => [item.id, item.readAt]), teacherReads, 'Student reads never mutate teacher notifications');
    } finally { T.page.off('request', observePublish); }
  });
});
