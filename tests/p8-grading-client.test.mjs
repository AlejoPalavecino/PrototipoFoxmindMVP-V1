import { gradingView } from './helpers/audit-grade-dto.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { loadTsModule } from './helpers/load-ts-module.mjs';
import { createClassroomClient } from '../apps/web/src/application/transport/classroom-client.ts';
const id = 'a1111111-1111-4111-8111-111111111111';
// Whitespace is collapsed so these source checks do not depend on how the formatter wraps code.
const flat = text => text.replace(/\s+/g, ' ');
test('private correction client sends canonical decimal text with fresh CSRF, never an attempt capability', async () => {
  const calls = []; let csrf = 0;
  const client = createClassroomClient({ csrfToken: async () => String(++csrf), fetch: async (path, options) => { calls.push({ path, ...options }); return Response.json(gradingView); } });
  const body = { revision: '4', overallGrade: '8.50', overallFeedback: null, questions: [] };
  await client.call(`/${id}/attempts/${id}/grading`, 'POST', body);
  assert.equal(calls[0].body, JSON.stringify(body)); assert.equal(calls[0].headers['X-CSRF-Token'], '1');
  assert.equal(calls[0].headers['X-Attempt-Editor'], undefined);
  await client.call(`/${id}/attempts/${id}/grading`); assert.equal(calls[1].method, 'GET'); assert.equal(calls[1].body, undefined);
  const malformed = createClassroomClient({ csrfToken: async () => 'fixture', fetch: async () => Response.json({}) });
  await assert.rejects(() => malformed.call(`/${id}/attempts/${id}/grading`), { code: 'SERVICE_UNAVAILABLE' });
});
test('actual all-type history keeps private saving separate from explicit saved-state publication', async () => {
  const history = flat(await readFile(new URL('../apps/web/src/application/workflows/activity-session/AttemptHistory.tsx', import.meta.url), 'utf8'));
  const editor = await readFile(new URL('../apps/web/src/features/grading/editing/GradingEditor.tsx', import.meta.url), 'utf8');
  assert.match(history, /teacher && attempt.status === 'SUBMITTED'.*Corregir intento/);
  assert.match(history, /<GradingEditor/); assert.match(editor, /Guardar corrección privada/);
  assert.match(editor, /overallGrade: data.activity.type === 'ASSIGNMENT'/); assert.match(await readFile(new URL('../apps/web/src/features/grading/editing/use-grading-draft.ts', import.meta.url), 'utf8'), /manualPoints/);
  assert.match(editor, /No se ha publicado/); assert.ok(!editor.includes('Aprobado'));
  assert.match(editor, /operations.save\(/);
  const saving = editor.slice(editor.indexOf('operations.save('), editor.indexOf('Guardar corrección privada'));
  assert.ok(!saving.includes('/publish-grade')); assert.ok(!saving.includes('confirm: true'));
  assert.match(editor, /canPublish = .*data.grade.id.*!data.grade.pending.*!dirty.*!busy/);
  assert.match(editor, /setConfirming\(true\)/); assert.match(editor, /Cancelar publicación/);
  assert.match(editor, /publication.publish\(data.revision\)/);
  const { createGradingEditingApi, createGradingPublicationApi } = loadTsModule('apps/web/src/features/grading/api.ts');
  const receipts = [], transport = { call: async (...args) => { receipts.push(args); return gradingView; } };
  const privateBody = { revision: '5', overallGrade: '8.50', overallFeedback: 'Privado', questions: [] };
  await createGradingEditingApi(transport, id, id).save(privateBody);
  assert.equal(receipts[0][0], '/' + id + '/attempts/' + id + '/grading');
  assert.equal(receipts[0][1], 'POST'); assert.deepEqual(receipts[0][2], privateBody);
  assert.equal('confirm' in receipts[0][2], false); assert.equal(receipts[0][0].includes('publish-grade'), false);
  await createGradingPublicationApi(transport, id, id).publish('5');
  assert.equal(receipts[1][0], '/' + id + '/attempts/' + id + '/publish-grade');
  assert.equal(receipts[1][1], 'POST'); assert.deepEqual(receipts[1][2], { revision: '5', confirm: true });
  const publishing = editor.slice(editor.indexOf('publication.publish('), editor.indexOf('Confirmar publicación</button>'));
  assert.ok(!publishing.includes('overallGrade')); assert.ok(!publishing.includes('saveAttempt'));
});
