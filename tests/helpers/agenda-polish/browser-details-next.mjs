const contrast = await page.evaluate(() => {
  const rgb = value => value.match(/[\d.]+/g).map(Number);
  const luminance = value => rgb(value).slice(0,3).map(x=>x/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4).reduce((sum,x,i)=>sum+x*[.2126,.7152,.0722][i],0);
  return ['h1','.p5-lead','.agenda-selected h2','.agenda-event h3','.agenda-header .primary','.agenda-legend','.agenda-date'].map(selector => {
    const el = document.querySelector(selector), style = getComputedStyle(el);
    let ancestor = el, background;
    while (ancestor) { const next = getComputedStyle(ancestor).backgroundColor; if (rgb(next)[3] !== 0) { background = next; break; } ancestor = ancestor.parentElement; }
    background ||= 'rgb(255,255,255)'; const a=luminance(style.color), b=luminance(background);
    return { selector, foreground: style.color, background, ratio: (Math.max(a,b)+.05)/(Math.min(a,b)+.05), font: style.fontFamily, size: style.fontSize, weight: style.fontWeight };
  });
});
assert.ok(contrast.every(item => item.ratio >= 4.5)); results.push({ action: 'contrast', values: contrast });
