await page.click('loc=role:button[name="Crear evento"]');
await page.waitForSelector('dialog[open]', { state: 'hidden' });
const created = await page.evaluate(() => JSON.parse(document.querySelector('[data-qa-action]').textContent));
assert.equal(created.at(-1).method, 'put'); assert.equal(created.at(-1).args[1].title, 'Evento sintético creado');
results.push({ action: 'create', calls: created });
await page.click('loc=role:button[name="Editar evento"]');
await page.fill('input[name="title"]', 'Evento sintético editado');
await page.click('loc=role:button[name="Guardar cambios"]');
await page.waitForSelector('dialog[open]', { state: 'hidden' });
const edited = await page.evaluate(() => JSON.parse(document.querySelector('[data-qa-action]').textContent));
assert.equal(edited.at(-1).method, 'replace'); assert.equal(edited.at(-1).args[1], 'fixture-r2');
results.push({ action: 'edit sends CAS revision', calls: edited });
