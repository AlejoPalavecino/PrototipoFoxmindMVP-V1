const fs = await import('node:fs/promises'), assert = await import('node:assert/strict');
const evidence = 'C:/Users/alejo/Documents/ProyectosAlejo/FoxMind/ProtipoFoxMind/docs/work-log/evidence/2026-10-25-agenda-polish';
const results = [];
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1536, height: 1024, deviceScaleFactor: 1, mobile: false });
await page.goto('http://127.0.0.1:53271/?mode=empty');
await page.waitForSelector('.agenda-selected', { state: 'visible' });
await page.click('loc=role:button[name="+ Nuevo evento"]');
await page.waitForSelector('dialog[open]', { state: 'visible' });
await page.click('loc=role:button[name="Crear evento"]');
await page.waitForSelector('input[name="title"][aria-invalid="true"]', { state: 'visible' });
const invalid = await page.evaluate(() => ({ focus: document.activeElement?.getAttribute('name'), calls: document.querySelector('[data-qa-action]').textContent, text: document.querySelector('dialog').innerText }));
assert.equal(invalid.focus, 'title'); assert.equal(invalid.calls, ''); results.push({ action: 'invalid blocks API and focuses title', ...invalid });
