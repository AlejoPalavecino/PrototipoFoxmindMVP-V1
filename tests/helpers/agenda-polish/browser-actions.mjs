await page.click('loc=role:button[name="Editar evento"]');
await page.fill('input[name="title"]', 'Cambios locales conservados');
await page.click('loc=role:button[name="Guardar cambios"]');
await page.waitForSelector('loc=role:button[name="Revisar versión guardada y conservar mis cambios"]', { state: 'visible' });
await page.click('loc=role:button[name="Revisar versión guardada y conservar mis cambios"]');
const conflict = await page.evaluate(() => ({ title: document.querySelector('input[name="title"]').value, text: document.querySelector('dialog').innerText, calls: JSON.parse(document.querySelector('[data-qa-action]').textContent) }));
assert.equal(conflict.title, 'Cambios locales conservados'); assert.equal(conflict.calls.at(-1).method, 'get');
assert.ok(conflict.text.includes('Versión guardada: Repasar contenidos')); results.push({ action: 'conflict review preserves local changes', ...conflict });
await fs.writeFile(evidence + '/actions-conflict.snapshot.txt', await page.snapshot({ scope: 'full_page' }));
await page.screenshot({ path: evidence + '/actions-conflict.png' });
await page.goto('http://127.0.0.1:53271/?mode=populated');
await page.waitForSelector('.agenda-event', { state: 'visible' });
await page.click('.agenda-upcoming button');
const opened = await page.evaluate(() => JSON.parse(document.querySelector('[data-qa-action]').textContent));
assert.equal(opened.classroomId, '11111111-1111-4111-8111-111111111111'); results.push({ action: 'open activity target', target: opened });
await page.click('loc=role:button[name="Mes siguiente"]');
await page.waitForFunction(() => document.querySelector('.agenda-month-head').textContent.toLowerCase().includes('noviembre'));
await page.click('loc=role:button[name="Mes anterior"]');
await page.waitForFunction(() => document.querySelector('.agenda-month-head').textContent.toLowerCase().includes('octubre'));
await page.click('loc=role:button[name="Hoy"]');
const today = await page.evaluate(() => ({ selected: document.querySelector('.agenda-day[aria-pressed="true"]').getAttribute('aria-current'), cells: document.querySelectorAll('.agenda-grid > button').length }));
assert.equal(today.selected, 'date'); assert.equal(today.cells, 42); results.push({ action: 'prev next and today', ...today });
await page.click('loc=role:button[name="Cambiar"]');
await page.selectOption('select', 'Asia/Tokyo');
const zone = await page.evaluate(() => ({ value: document.querySelector('select').value, deadline: document.querySelector('.agenda-upcoming').innerText }));
assert.equal(zone.value, 'Asia/Tokyo'); assert.ok(zone.deadline.includes('22:00')); results.push({ action: 'viewer zone change preserves classroom deadline', ...zone });
