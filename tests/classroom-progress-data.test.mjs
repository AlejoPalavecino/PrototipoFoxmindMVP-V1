import test from 'node:test';
import assert from 'node:assert/strict';
import { withProgressFixture, tableHash, academicTables } from './p8-progress-helpers.mjs';
import { saveComplete, publish } from './p8-publication-helpers.mjs';

test('persisted review progress keeps effective grades, private status and unit teaching separate', { timeout: 180000 }, async () => {
  await withProgressFixture(async f => {
    const item = await f.createAssignment('Recorrido sintético');
    const first = await f.submit(item);
    const teacherRow = async () => (await f.service.getProgress(f.T, f.room)).students.find(row => row.studentId === f.student).activities.find(row => row.id === item.id);
    const studentRow = async () => (await f.service.getProgress(f.S, f.room)).activities.find(row => row.id === item.id);
    assert.deepEqual((await teacherRow()).review, { attemptId: first, state: 'pending' });
    assert.equal(Object.hasOwn(await studentRow(), 'review'), false);
    await saveComplete(f, first, '2', '0');
    assert.deepEqual((await teacherRow()).review, { attemptId: first, state: 'saved' });
    assert.equal((await studentRow()).grade, null);
    assert.equal((await studentRow()).publishedAttemptId, null);
    await publish(f, first);
    assert.deepEqual((await teacherRow()).review, { attemptId: first, state: 'published' });
    assert.equal((await studentRow()).grade, '0.00');
    assert.equal((await studentRow()).publishedAttemptId, first);
    await f.reopen(item); const second = await f.submit(item);
    assert.deepEqual((await teacherRow()).review, { attemptId: second, state: 'pending' });
    assert.equal((await teacherRow()).firstSubmission.id, first);
    assert.equal((await teacherRow()).grade, '0.00');
    await saveComplete(f, second, '2', '9');
    assert.deepEqual((await teacherRow()).review, { attemptId: second, state: 'saved' });
    assert.equal((await studentRow()).grade, '0.00');
    assert.equal((await studentRow()).publishedAttemptId, first);
    assert.equal(JSON.stringify(await studentRow()).includes(second), false, 'latest private review attempt must not leak into own progress');
    const member = await f.service.getStudentProgress(f.T, f.room, f.student);
    assert.deepEqual(member.activities[0].review, { attemptId: second, state: 'saved' });
    const before = await tableHash(f.pool, academicTables);
    await assert.rejects(f.service.getStudentProgress(f.S, f.room, f.student), { code: 'FORBIDDEN' });
    await assert.rejects(f.service.getProgress(f.F, f.room), { code: 'FORBIDDEN' });
    assert.equal(await tableHash(f.pool, academicTables), before);
    const detail = await f.service.detail(f.T, f.room), unit = detail.units[0];
    await f.service.changePlan(f.T, f.room, { revision: detail.revision, operation: { action: 'setTopicState', id: unit.topics[0].id, status: 'TAUGHT' } });
    const own = await f.service.getProgress(f.S, f.room);
    assert.deepEqual(own.plan.units, [{ id: unit.id, name: unit.name, total: 1, taught: 1 }]);
    assert.equal(JSON.stringify(own).includes('"review"'), false);
    const retired = await f.createAssignment('Retirada sin entregas');
    await f.change({ action: 'withdraw', id: retired.id });
    const hash = await tableHash(f.pool, academicTables), withdrawn = await f.service.getProgress(f.S, f.room);
    assert.deepEqual(withdrawn.plan, own.plan);
    assert.equal(withdrawn.activities.some(row => row.id === retired.id), false);
    assert.equal(withdrawn.activities.find(row => row.id === item.id).grade, '0.00');
    assert.equal(await tableHash(f.pool, academicTables), hash, 'reading progress does not modify academic state');
  });
});
